"""
Train NanoDet barcode detector.
Dataset: Synthetic barcodes generated by data/synthetic_barcodes.py
License: MIT
"""

import argparse
import json
import os

import torch
import torch.optim as optim
from torch.utils.data import DataLoader
from torch.cuda.amp import GradScaler, autocast

from data.synthetic_barcodes import BarcodeDetectionDataset
from models.nanodet import NanoDetBarcode


def train(args):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Using device: {device}")

    model = NanoDetBarcode(num_classes=4).to(device)
    print(
        f"Model parameters: {sum(p.numel() for p in model.parameters()) / 1e6:.2f}M"
    )

    train_dataset = BarcodeDetectionDataset(
        num_samples=args.num_samples,
        image_size=(320, 320),
        num_classes=4,
        augment=True,
    )
    train_loader = DataLoader(
        train_dataset,
        batch_size=args.batch_size,
        shuffle=True,
        num_workers=args.workers,
        pin_memory=True,
    )

    val_dataset = BarcodeDetectionDataset(
        num_samples=args.num_val,
        image_size=(320, 320),
        num_classes=4,
        augment=False,
    )
    val_loader = DataLoader(
        val_dataset,
        batch_size=args.batch_size,
        shuffle=False,
        num_workers=args.workers,
        pin_memory=True,
    )

    optimizer = optim.AdamW(
        model.parameters(), lr=args.lr, weight_decay=args.weight_decay
    )
    scheduler = optim.lr_scheduler.CosineAnnealingLR(
        optimizer, T_max=args.epochs, eta_min=1e-6
    )
    scaler = GradScaler() if args.amp else None

    best_loss = float("inf")
    os.makedirs(args.output_dir, exist_ok=True)

    for epoch in range(args.epochs):
        model.train()
        train_loss = 0.0

        for batch_idx, (images, targets) in enumerate(train_loader):
            images = images.to(device)
            targets = {
                k: v.to(device) for k, v in targets.items()
            }

            optimizer.zero_grad()

            if args.amp:
                with autocast():
                    boxes, scores, classes = model(images)
                    loss = compute_loss(
                        boxes, scores, classes, targets
                    )
                scaler.scale(loss).backward()
                scaler.unscale_(optimizer)
                torch.nn.utils.clip_grad_norm_(model.parameters(), 10.0)
                scaler.step(optimizer)
                scaler.update()
            else:
                boxes, scores, classes = model(images)
                loss = compute_loss(boxes, scores, classes, targets)
                loss.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(), 10.0)
                optimizer.step()

            train_loss += loss.item()

            if batch_idx % args.log_interval == 0:
                print(
                    f"Epoch {epoch:3d} [{batch_idx:4d}/{len(train_loader):4d}] "
                    f"Loss: {loss.item():.4f}"
                )

        scheduler.step()
        avg_train_loss = train_loss / len(train_loader)

        model.eval()
        val_loss = 0.0
        with torch.no_grad():
            for images, targets in val_loader:
                images = images.to(device)
                targets = {k: v.to(device) for k, v in targets.items()}
                boxes, scores, classes = model(images)
                loss = compute_loss(boxes, scores, classes, targets)
                val_loss += loss.item()

        avg_val_loss = val_loss / len(val_loader)

        print(
            f"Epoch {epoch:3d} | Train Loss: {avg_train_loss:.4f} | "
            f"Val Loss: {avg_val_loss:.4f} | LR: {scheduler.get_last_lr()[0]:.2e}"
        )

        if avg_val_loss < best_loss:
            best_loss = avg_val_loss
            torch.save(
                model.state_dict(),
                os.path.join(args.output_dir, "nanodet_best.pth"),
            )
            print(f"  -> Saved best model (val_loss={best_loss:.4f})")

        if (epoch + 1) % args.save_interval == 0:
            torch.save(
                {
                    "epoch": epoch,
                    "model_state_dict": model.state_dict(),
                    "optimizer_state_dict": optimizer.state_dict(),
                    "loss": avg_val_loss,
                },
                os.path.join(args.output_dir, f"checkpoint_{epoch:04d}.pth"),
            )

    model.load_state_dict(
        torch.load(
            os.path.join(args.output_dir, "nanodet_best.pth"),
            map_location=device,
        )
    )

    onnx_path = os.path.join(args.output_dir, "nanodet_barcode.onnx")
    model.export_onnx(onnx_path)
    print(f"Exported ONNX to {onnx_path}")


def compute_loss(boxes, scores, classes, targets):
    classification_loss = torch.nn.functional.binary_cross_entropy(
        scores, targets["scores"].float()
    )

    pos_mask = targets["scores"] > 0

    if pos_mask.sum() > 0:
        reg_loss = torch.nn.functional.smooth_l1_loss(
            boxes[pos_mask], targets["boxes"][pos_mask]
        )
    else:
        reg_loss = torch.tensor(0.0, device=boxes.device)

    return classification_loss + 2.0 * reg_loss


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Train NanoDet barcode detector")
    parser.add_argument("--num-samples", type=int, default=100000)
    parser.add_argument("--num-val", type=int, default=5000)
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--epochs", type=int, default=100)
    parser.add_argument("--lr", type=float, default=1e-3)
    parser.add_argument("--weight-decay", type=float, default=1e-4)
    parser.add_argument("--amp", action="store_true", default=True)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--log-interval", type=int, default=100)
    parser.add_argument("--save-interval", type=int, default=10)
    parser.add_argument(
        "--output-dir", type=str, default="./checkpoints/nanodet"
    )
    args = parser.parse_args()
    train(args)
